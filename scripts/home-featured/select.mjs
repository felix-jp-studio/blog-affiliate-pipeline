/**
 * Monthly homepage "おすすめ記事" selection from weekly GSC page CSVs.
 * Candidates per category are the hub mesh featured slugs that are published;
 * they rank by clicks, then impressions, then average position. Articles with
 * no GSC data keep the previous picks first, then hub mesh order.
 */
import { parseCsv } from "../lib/csv.mjs";

export const HOME_CATEGORIES = ["sim", "hikari", "trouble", "cost"];
export const PICKS_PER_CATEGORY = 2;

const PAGES_CSV_PATTERN = /^gsc-pages-(\d{8})\.csv$/;

/** Newest `weeks` weekly page CSV filenames, oldest first. */
export function latestPagesCsvNames(filenames, weeks) {
  return filenames
    .filter((name) => PAGES_CSV_PATTERN.test(name))
    .sort()
    .slice(-weeks);
}

export function slugFromPageUrl(url) {
  let pathname;
  try {
    pathname = new URL(url).pathname;
  } catch {
    return null;
  }
  const match = pathname.match(/^\/articles\/([^/]+)\/?$/);
  return match ? decodeURIComponent(match[1]) : null;
}

/** Sum clicks / impressions per slug; position is impression-weighted. */
export function aggregatePageMetrics(csvTexts) {
  const totals = new Map();
  for (const text of csvTexts) {
    for (const row of parseCsv(text).rows) {
      const slug = slugFromPageUrl(row.Page);
      if (!slug) continue;
      const clicks = Number.parseFloat(row.Clicks) || 0;
      const impressions = Number.parseFloat(row.Impressions) || 0;
      const position = Number.parseFloat(row.Position) || 0;
      const total = totals.get(slug) ?? { clicks: 0, impressions: 0, positionSum: 0 };
      total.clicks += clicks;
      total.impressions += impressions;
      total.positionSum += position * impressions;
      totals.set(slug, total);
    }
  }

  const metrics = new Map();
  for (const [slug, total] of totals) {
    metrics.set(slug, {
      clicks: total.clicks,
      impressions: total.impressions,
      position: total.impressions > 0 ? total.positionSum / total.impressions : Infinity,
    });
  }
  return metrics;
}

const NO_DATA = { clicks: 0, impressions: 0, position: Infinity };

/**
 * @param {object} input
 * @param {Record<string, { featured: { slug: string }[] }>} input.mesh
 * @param {Set<string>} input.publishedSlugs
 * @param {Map<string, { clicks: number, impressions: number, position: number }>} input.metrics
 * @param {Record<string, string[]>} input.previous
 */
export function selectHomeFeatured({
  mesh,
  publishedSlugs,
  metrics,
  previous = {},
  perCategory = PICKS_PER_CATEGORY,
}) {
  const picks = {};
  for (const category of HOME_CATEGORIES) {
    const featured = mesh[category]?.featured ?? [];
    const previousPicks = previous[category] ?? [];
    const candidates = featured
      .map((item, meshIndex) => ({
        slug: item.slug,
        meshIndex,
        previousIndex: previousPicks.includes(item.slug)
          ? previousPicks.indexOf(item.slug)
          : Infinity,
        ...(metrics.get(item.slug) ?? NO_DATA),
      }))
      .filter((candidate) => publishedSlugs.has(candidate.slug));

    candidates.sort(
      (a, b) =>
        b.clicks - a.clicks ||
        b.impressions - a.impressions ||
        compareAscending(a.position, b.position) ||
        compareAscending(a.previousIndex, b.previousIndex) ||
        a.meshIndex - b.meshIndex,
    );
    picks[category] = candidates.slice(0, perCategory).map((candidate) => candidate.slug);
  }
  return picks;
}

function compareAscending(a, b) {
  if (a === b) return 0;
  return a < b ? -1 : 1;
}

/** Short label such as "gsc-pages 20260918-20261009 (4 weeks)". */
export function describeSources(sources) {
  const dates = sources.map((name) => name.match(PAGES_CSV_PATTERN)?.[1]).filter(Boolean);
  if (dates.length === 0) return "no GSC data";
  const weeks = `${dates.length} week${dates.length === 1 ? "" : "s"}`;
  return `gsc-pages ${dates[0]}-${dates.at(-1)} (${weeks})`;
}

export function renderHomeFeaturedModule({ picks, updatedAt, sources }) {
  const entries = HOME_CATEGORIES.filter((category) => picks[category]?.length)
    .map(
      (category) =>
        `  ${category}: [${picks[category].map((slug) => JSON.stringify(slug)).join(", ")}],`,
    )
    .join("\n");
  const basis = describeSources(sources);

  return `// Generated by scripts/update-home-featured.mjs (monthly). Do not edit by hand.
import type { CategorySlug } from "./category-meta";

/** Last selection date (JST) and the range of GSC page CSVs it was based on. */
export const homeFeaturedUpdatedAt = ${JSON.stringify(updatedAt)};
export const homeFeaturedBasis = ${JSON.stringify(basis)};

/** Homepage picks: ${PICKS_PER_CATEGORY} per category, ranked by GSC clicks / impressions. */
export const homeFeaturedSlugs: Partial<Record<CategorySlug, string[]>> = {
${entries}
};
`;
}
